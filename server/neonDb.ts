import { Pool } from '@neondatabase/serverless';

let pool: Pool | null = null;

/**
 * Lazy initialization helper for Neon PostgreSQL connection pool.
 * Gracefully handles missing DATABASE_URL without crashing the server startup.
 */
export function getDbPool(): Pool | null {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    return null;
  }
  if (!pool) {
    try {
      pool = new Pool({ connectionString });
      console.log('🐘 [Neon PostgreSQL] Initialized connection pool successfully.');
    } catch (err) {
      console.error('⚠️ [Neon PostgreSQL] Failed to initialize connection pool:', err);
      return null;
    }
  }
  return pool;
}

/**
 * Execute a SQL query against Neon PostgreSQL.
 */
export async function queryNeon(text: string, params?: any[]) {
  const dbPool = getDbPool();
  if (!dbPool) {
    throw new Error('DATABASE_URL is not configured in environment variables.');
  }
  const start = Date.now();
  const res = await dbPool.query(text, params);
  const duration = Date.now() - start;
  // console.log(`🐘 [Neon SQL] ${text.slice(0, 50)}... (${duration}ms, ${res.rowCount} rows)`);
  return res;
}

